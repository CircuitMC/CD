S["nautilus_armor_inventory"] = S["nautilus_armor"]


def _hint(rows):
    def fn(ctx):
        c = Canvas(ctx)
        rows_ = [r for r in rows.strip("\n").split("\n")]
        # vertically center the drawing
        oy = max(0, (16 - len(rows_)) // 2)
        cells = {(i, j + oy) for j, r in enumerate(rows_) for i, ch in enumerate(r) if ch == "#"}
        for (x, y) in cells:
            dark = (x + 1, y) not in cells or (x, y + 1) not in cells
            c.px(x, y, EDGE if dark else FILL, 0.9)
        return c.tex()
    return fn


for _k, _rows in S.items():
    register(f"gui/sprites/container/slot/{_k}", _hint(_rows))
