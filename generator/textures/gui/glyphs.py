"""CircuitMC pixel typeface (original design).

Glyphs live in "em" texel coordinates: x from 0 (left aligned), y = 0 is the
cap-height top, y = 6 the last row sitting on the baseline, y = 7..8 the
descender, y = -1..-3 room for accents. Font sheets map em rows to cell rows.

`glyph(ch)` returns a frozenset of (x, y) cells or None when the character is
not designed (the font provider override then leaves it to the fallback font).
Many characters are derived automatically: accented letters via Unicode
decomposition + mark shapes, small capitals, turned/reversed letters,
superscripts, circled letters, fractions and "WITH STROKE/DESCENDER" variants.
"""
import functools
import unicodedata


def _parse(spec):
    """'2|.##. #..#' -> set of cells; leading 'N|' gives the first em row."""
    y0 = 0
    if "|" in spec:
        a, spec = spec.split("|", 1)
        y0 = int(a)
    cells = set()
    for j, row in enumerate(spec.split()):
        for i, c in enumerate(row):
            if c == "#":
                cells.add((i, y0 + j))
    return frozenset(cells)


