VIET_SIDE = {"̀", "́", "̉", "̃"}


def _bounds(cells):
    xs = [x for x, _ in cells]
    ys = [y for _, y in cells]
    return min(xs), max(xs), min(ys), max(ys)


def _stamp(cells, spec, x0, y0):
    out = set(cells)
    for (x, y) in _parse(spec):
        out.add((x + x0, y + y0))
    return out


def _mark_size(spec):
    rows = spec.split()
    return max(len(r) for r in rows), len(rows)


def _compose(base, marks):
    above = [m for m in marks if m in MARKS_ABOVE]
    below = [m for m in marks if m in MARKS_BELOW]
    horn = "̛" in marks
    if len(above) + len(below) + horn != len(marks):
        return None
    if above and base in "ij":
        base = {"i": "ı", "j": "ȷ"}[base]
    g = glyph(base)
    if g is None:
        return None
    cells = set(g)
    x0, x1, y0, y1 = _bounds(cells)
    greek_cap = unicodedata.category(base) == "Lu" and "GREEK" in unicodedata.name(base, "")
    if greek_cap and above:
        # Greek capitals carry their marks on the left: shift the letter right.
        widths = sum(_mark_size(MARKS_ABOVE[m])[0] for m in above)
        cells = {(x + widths + 1, y) for x, y in cells}
        x = 0
        for m in above:
            w, h = _mark_size(MARKS_ABOVE[m])
            cells = _stamp(cells, MARKS_ABOVE[m], x, y0 - 0)
            x += w
        return frozenset(cells)
    cx = (x0 + x1) / 2
    top = y0
    if horn:
        cells.add((x1 + 1, y0 - 1))
        cells.add((x1 + 1, y0))
    if len(above) == 2 and above[1] in VIET_SIDE and above[0] in ("̂", "̆"):
        w0, h0 = _mark_size(MARKS_ABOVE[above[0]])
        mx = int(round(cx - (w0 - 1) / 2))
        cells = _stamp(cells, MARKS_ABOVE[above[0]], mx, top - 1 - h0)
        w1, h1 = _mark_size(MARKS_ABOVE[above[1]])
        cells = _stamp(cells, MARKS_ABOVE[above[1]], mx + w0, top - 1 - h0 - 1)
    else:
        total = sum(_mark_size(MARKS_ABOVE[m])[1] for m in above)
        room = top + 3  # rows available above the letter (em row -3 is the cell top)
        gap = 1 if total + len(above) <= room else 0
        y = top - gap
        for m in above:
            spec = MARKS_ABOVE[m]
            w, h = _mark_size(spec)
            if gap == 0 and h == 3 and len(above) > 1:
                spec = spec  # stacked ring etc.: allowed to touch
            y -= h
            cells = _stamp(cells, spec, int(round(cx - (w - 1) / 2)), y)
            y -= gap if len(above) > 1 and total + 2 * len(above) <= room else 0
    yb = max(y1, 6) + 1
    for m in below:
        spec = MARKS_BELOW[m]
        w, h = _mark_size(spec)
        if m == "̨":
            mx = x1 - 1
        else:
            mx = int(round(cx - (w - 1) / 2))
        if y1 > 6 and m != "̨":
            yb = y1 + 1
        cells = _stamp(cells, spec, mx, yb + (1 if m in ("̣", "̤") else 0))
        yb += h
    return frozenset(cells)


