# ----------------------------------------------------------------- derivation
_TRANSFORM_PREFIX = "~"  # alias "~X" = X turned 180 degrees


def _turn(cells, capital):
    x0, x1, _, _ = _bounds(cells)
    c = 6 if capital else 8
    return frozenset((x1 - (x - x0), c - y) for x, y in cells)


def _mirror(cells):
    x0, x1, _, _ = _bounds(cells)
    return frozenset((x1 - (x - x0), y) for x, y in cells)


def _flipv(cells, capital):
    c = 6 if capital else 8
    return frozenset((x, c - y) for x, y in cells)


def _shift(cells, dx=0, dy=0):
    return frozenset((x + dx, y + dy) for x, y in cells)


def _small_cap(cap):
    g = glyph(cap)
    if g is None:
        return None
    rows = [0, 1, 3, 5, 6]
    return frozenset((x, 2 + rows.index(y)) for x, y in g if y in rows)


def _super(cells, sub=False):
    return _shift(cells, 0, 3 if sub else 0)


def _concat(*parts, gap=1, maxw=8):
    out, x = set(), 0
    for p in parts:
        if p is None:
            return None
        if not p:
            x += 3
            continue
        x0, x1, _, _ = _bounds(p)
        out |= {(cx - x0 + x, cy) for cx, cy in p}
        x += x1 - x0 + 1 + gap
    if out and _bounds(out)[1] >= maxw:
        return None
    return frozenset(out)


def _circled(inner):
    ring = _parse("..#####.. .#.....#. #.......# #.......# #.......# #.......# #.......# .#.....#. ..#####..")
    ring = _shift(ring, 0, -2)
    x0, x1, y0, y1 = _bounds(inner)
    w, h = x1 - x0 + 1, y1 - y0 + 1
    ox, oy = 4 - (w - 1) // 2 - (w % 2 == 0), 2 - (h - 1) // 2
    return frozenset(ring | {(x - x0 + ox, y - y0 + oy) for x, y in inner})


def _with_stroke(cells, capital, lower_asc):
    x0, x1, y0, y1 = _bounds(cells)
    stem = min(x for x, y in cells if y == max(y0, 2 if not capital else 0) + 2) if cells else 0
    row = 3 if capital else (1 if lower_asc else 4)
    out = set(cells)
    shift = 1 if stem == 0 else 0
    out = {(x + shift, y) for x, y in out}
    stem += shift
    for dx in (-1, 0, 1):
        out.add((stem + dx, row))
    return frozenset(out)



def _box(name):
    """Box drawing / block element glyphs on the full 8x8 cell (em rows 0..7)."""
    full = {(x, y) for x in range(8) for y in range(8)}
    if name == "FULL BLOCK":
        return frozenset(full)
    if name == "LOWER HALF BLOCK":
        return frozenset((x, y) for x, y in full if y >= 4)
    if name == "UPPER HALF BLOCK":
        return frozenset((x, y) for x, y in full if y < 4)
    if name == "LEFT HALF BLOCK":
        return frozenset((x, y) for x, y in full if x < 4)
    if name == "RIGHT HALF BLOCK":
        return frozenset((x, y) for x, y in full if x >= 4)
    if name == "LIGHT SHADE":
        return frozenset((x, y) for x, y in full if x % 2 == 0 and y % 2 == 0)
    if name == "MEDIUM SHADE":
        return frozenset((x, y) for x, y in full if (x + y) % 2 == 0)
    if name == "DARK SHADE":
        return frozenset((x, y) for x, y in full if not (x % 2 == 1 and y % 2 == 1))
    if not name.startswith("BOX DRAWINGS "):
        return None
    words = name[len("BOX DRAWINGS "):].split()
    arms = {"UP": 0, "DOWN": 0, "LEFT": 0, "RIGHT": 0}
    weight = 1
    pending = []
    for w in words:
        if w in ("LIGHT", "HEAVY"):
            weight = 1
        elif w == "DOUBLE":
            weight = 2
        elif w == "SINGLE":
            weight = 1
        elif w in ("VERTICAL", "HORIZONTAL"):
            pending += ["UP", "DOWN"] if w == "VERTICAL" else ["LEFT", "RIGHT"]
            for a in pending:
                arms[a] = max(arms[a], weight)
            pending = []
        elif w in arms:
            pending.append(w)
        elif w == "AND":
            for a in pending:
                arms[a] = max(arms[a], weight)
            pending = []
    for a in pending:
        arms[a] = max(arms[a], weight)
    c = set()
    vx = (3,) if max(arms["UP"], arms["DOWN"]) < 2 else (2, 4)
    hy = (3,) if max(arms["LEFT"], arms["RIGHT"]) < 2 else (2, 4)
    lo_x, hi_x = min(vx), max(vx)
    lo_y, hi_y = min(hy), max(hy)
    for x in vx:
        if arms["UP"]:
            c |= {(x, y) for y in range(0, (hi_y if x in (lo_x,) or len(vx) == 1 else lo_y) + 1)}
    for x in vx:
        if arms["DOWN"]:
            c |= {(x, y) for y in range(lo_y if len(vx) == 1 or x == lo_x else lo_y, 8)}
    for y in hy:
        if arms["LEFT"]:
            c |= {(x, y) for x in range(0, hi_x + 1)}
        if arms["RIGHT"]:
            c |= {(x, y) for x in range(lo_x, 8)}
    return frozenset(c) if c else None

@functools.lru_cache(maxsize=None)
def glyph(ch):
    if not ch:
        return None
    if ch in B:
        return _parse(B[ch]) if B[ch] else None
    if ch in ALIASES:
        a = ALIASES[ch]
        if a.startswith(_TRANSFORM_PREFIX) and len(a) > 1:
            g = glyph(a[1:])
            if g is None:
                return None
            cap = a[1:].isupper() or a[1] in "∀"
            return _turn(g, cap)
        return glyph(a) if a != ch else None
    nfd = unicodedata.normalize("NFD", ch)
    if len(nfd) > 1 and not unicodedata.combining(nfd[0]):
        g = _compose(nfd[0], nfd[1:])
        if g is not None:
            return g
    name = unicodedata.name(ch, "")
    if not name:
        return None
    bx = _box(name)
    if bx is not None:
        return bx
    nfkd = unicodedata.decomposition(ch)
    if nfkd.startswith("<super>"):
        base = chr(int(nfkd.split()[1], 16))
        t = tiny(base)
        return _super(t) if t else None
    if nfkd.startswith("<sub>"):
        base = chr(int(nfkd.split()[1], 16))
        t = tiny(base)
        return _super(t, sub=True) if t else None
    if nfkd.startswith("<circle>"):
        text = "".join(chr(int(c, 16)) for c in nfkd.split()[1:])
        inner = None
        if len(text) == 1:
            inner = tiny(text)
        elif len(text) == 2:
            a, b = tiny(text[0]), tiny(text[1])
            if a and b:
                inner = _concat(a, b, gap=0 if text[0] == "1" else 1, maxw=9)
                if text[0] == "1":
                    inner = _concat(_parse("# # # # #"), b, gap=1, maxw=9)
        return _circled(inner) if inner else None
    if nfkd.startswith("<fraction>"):
        num, den = nfkd.split()[1:][0], nfkd.split()[-1]
        num, den = chr(int(num, 16)), chr(int(den, 16))
        a, b = tiny(num), tiny(den, 4, 3)
        if a and b:
            slash = {(5, 0), (4, 1), (4, 2), (3, 3), (3, 4), (3, 5), (2, 6), (2, 7)}
            return frozenset(a | b | slash)
        return None
    if nfkd.startswith("<compat>") or nfkd.startswith("<font>"):
        parts = [chr(int(c, 16)) for c in nfkd.split()[1:]]
        if len(parts) == 1:
            return glyph(parts[0])
        return _concat(*[glyph(p) for p in parts], maxw=9)
    capital = " CAPITAL " in name or name.startswith("LATIN LETTER SMALL CAPITAL")
    for key in ("LATIN LETTER SMALL CAPITAL ", "GREEK LETTER SMALL CAPITAL ", "CYRILLIC LETTER SMALL CAPITAL "):
        if name.startswith(key):
            rest = name[len(key):]
            script = key.split()[0]
            try:
                return _small_cap(unicodedata.lookup(f"{script} CAPITAL LETTER {rest}"))
            except KeyError:
                return None
    for word, fn in (("TURNED ", "turn"), ("REVERSED ", "mirror"), ("INVERTED ", "flip")):
        if word in name:
            try:
                base = unicodedata.lookup(name.replace(word, "", 1))
            except KeyError:
                continue
            g = glyph(base)
            if g is None:
                continue
            if fn == "turn":
                return _turn(g, capital)
            if fn == "mirror":
                return _mirror(g)
            return _flipv(g, capital)
    for suffix in (" WITH STROKE", " WITH BAR", " WITH DESCENDER", " WITH TAIL", " WITH HOOK",
                   " WITH MIDDLE TILDE", " WITH RETROFLEX HOOK", " WITH PALATAL HOOK", " WITH CURL",
                   " WITH LEFT HOOK", " WITH LONG LEG", " WITH MIDDLE HOOK", " WITH STROKE AND DESCENDER",
                   " WITH DOT ABOVE", " WITH TOPBAR", " WITH SWASH TAIL", " WITH LOOP", " WITH DIAGONAL STROKE",
                   " WITH VERTICAL STROKE", " WITH UPTURN", " WITH ACUTE", " WITH DOUBLE GRAVE",
                   " WITH HORN", " WITH TICK"):
        if name.endswith(suffix):
            try:
                base = unicodedata.lookup(name[: -len(suffix)])
            except KeyError:
                return None
            g = glyph(base)
            if g is None:
                return None
            x0, x1, y0, y1 = _bounds(g)
            lower_asc = not capital and y0 == 0
            if suffix in (" WITH STROKE", " WITH BAR", " WITH DIAGONAL STROKE", " WITH VERTICAL STROKE"):
                return _with_stroke(g, capital, lower_asc)
            if suffix in (" WITH DESCENDER", " WITH TAIL", " WITH SWASH TAIL", " WITH LONG LEG",
                          " WITH STROKE AND DESCENDER"):
                c = set(g)
                if suffix == " WITH STROKE AND DESCENDER":
                    c = set(_with_stroke(g, capital, lower_asc))
                    x0, x1, y0, y1 = _bounds(c)
                c.add((x1, y1 + 1))
                return frozenset(c)
            if suffix in (" WITH HOOK", " WITH MIDDLE HOOK", " WITH LEFT HOOK", " WITH UPTURN"):
                c = set(g)
                if capital or y0 == 0:
                    c.add((x1 + 1, y0))
                    c.discard((x1, y0)) if (x1 + 1, y0 + 1) in c else None
                    if not any((x1, y) in c for y in range(y0, y0 + 1)):
                        c.add((x1, y0))
                else:
                    c.add((x1, y1 + 1))
                    c.add((x1 - 1, y1 + 2))
                return frozenset(c)
            if suffix in (" WITH RETROFLEX HOOK", " WITH PALATAL HOOK", " WITH CURL", " WITH LOOP"):
                c = set(g)
                c.add((x1 + 1, y1 + 1))
                return frozenset(c)
            if suffix == " WITH MIDDLE TILDE":
                c = set(g) | {(x0 - 1 + i, 3 + (i % 2 == 0)) for i in range(x1 - x0 + 3)}
                return _shift(frozenset(c), 1 if x0 == 0 else 0)
            if suffix == " WITH DOT ABOVE":
                return _compose(base, "̇")
            if suffix in (" WITH TOPBAR", " WITH TICK"):
                c = set(g) | {(x0, y0 - 1), (x0 + 1, y0 - 1)}
                return frozenset(c)
            if suffix == " WITH ACUTE":
                return _compose(base, "́")
            if suffix == " WITH DOUBLE GRAVE":
                return _compose(base, "̏")
            if suffix == " WITH HORN":
                return _compose(base, "̛")
    if name.startswith("LATIN SMALL LIGATURE ") or name.startswith("LATIN CAPITAL LIGATURE ") \
            or name.startswith("LATIN CAPITAL LETTER ") and len(name.split()[-1]) == 2 \
            or name.startswith("LATIN SMALL LETTER ") and len(name.split()[-1]) == 2:
        letters = name.split()[-1]
        if letters.isalpha() and len(letters) in (2, 3):
            small = " SMALL " in name
            parts = [glyph(c.lower() if small else c) for c in letters]
            return _concat(*parts, maxw=9)
    if name.startswith("CYRILLIC SMALL LETTER ") or name.startswith("GREEK SMALL LETTER "):
        try:
            cap = unicodedata.lookup(name.replace("SMALL", "CAPITAL", 1))
        except KeyError:
            return None
        if cap.lower() == ch or True:
            return _small_cap(cap)
    if name.startswith("MODIFIER LETTER SMALL ") or name.startswith("MODIFIER LETTER CAPITAL "):
        base = name.split()[-1]
        t = tiny(base.lower() if "SMALL" in name else base)
        return _super(t) if t else None
    return None
